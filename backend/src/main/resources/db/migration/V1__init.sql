CREATE SEQUENCE order_number_seq START WITH 1001 INCREMENT BY 1;

CREATE TABLE restaurants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    description VARCHAR(500) NOT NULL,
    logo_url VARCHAR(500),
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE restaurant_branches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id BIGINT NOT NULL REFERENCES restaurants (id),
    name VARCHAR(120) NOT NULL,
    address_line VARCHAR(200) NOT NULL,
    city VARCHAR(80) NOT NULL,
    state VARCHAR(80) NOT NULL,
    postal_code VARCHAR(12) NOT NULL,
    phone VARCHAR(15) NOT NULL,
    opens_at TIME(0) WITHOUT TIME ZONE NOT NULL,
    closes_at TIME(0) WITHOUT TIME ZONE NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    accepting_orders BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_branches_restaurant ON restaurant_branches (restaurant_id);
CREATE INDEX idx_branches_active ON restaurant_branches (active);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(80) NOT NULL,
    email VARCHAR(160) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    phone VARCHAR(15) NOT NULL,
    role VARCHAR(32) NOT NULL,
    branch_id BIGINT REFERENCES restaurant_branches (id),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    token_version INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT ck_users_role CHECK (role IN ('CUSTOMER', 'KITCHEN_STAFF', 'RESTAURANT_ADMIN'))
);

CREATE INDEX idx_users_branch ON users (branch_id);

CREATE TABLE menu_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(60) NOT NULL,
    description VARCHAR(200),
    display_order INTEGER NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_categories_name UNIQUE (name)
);

CREATE TABLE menu_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT NOT NULL REFERENCES menu_categories (id),
    name VARCHAR(120) NOT NULL,
    description VARCHAR(500) NOT NULL,
    price NUMERIC(10, 2) NOT NULL,
    vegetarian BOOLEAN NOT NULL,
    image_url VARCHAR(500),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    popular BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_menu_items_price CHECK (price > 0)
);

CREATE INDEX idx_menu_items_category ON menu_items (category_id);
CREATE INDEX idx_menu_items_active ON menu_items (active);

CREATE TABLE branch_menu_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id BIGINT NOT NULL REFERENCES restaurant_branches (id),
    menu_item_id BIGINT NOT NULL REFERENCES menu_items (id),
    available BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_branch_menu UNIQUE (branch_id, menu_item_id)
);

CREATE INDEX idx_branch_menu_item ON branch_menu_items (menu_item_id);

CREATE TABLE carts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES users (id),
    branch_id BIGINT REFERENCES restaurant_branches (id),
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_carts_customer UNIQUE (customer_id)
);

CREATE TABLE cart_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cart_id BIGINT NOT NULL REFERENCES carts (id) ON DELETE CASCADE,
    menu_item_id BIGINT NOT NULL REFERENCES menu_items (id),
    quantity INTEGER NOT NULL,
    CONSTRAINT uq_cart_item UNIQUE (cart_id, menu_item_id),
    CONSTRAINT ck_cart_item_qty CHECK (quantity > 0 AND quantity <= 20)
);

CREATE TABLE customer_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number VARCHAR(20) NOT NULL,
    customer_id BIGINT NOT NULL REFERENCES users (id),
    branch_id BIGINT NOT NULL REFERENCES restaurant_branches (id),
    order_type VARCHAR(32) NOT NULL,
    status VARCHAR(32) NOT NULL,
    customer_name VARCHAR(80) NOT NULL,
    customer_phone VARCHAR(15) NOT NULL,
    delivery_address VARCHAR(300),
    special_instructions VARCHAR(300),
    subtotal NUMERIC(10, 2) NOT NULL,
    tax_amount NUMERIC(10, 2) NOT NULL,
    delivery_fee NUMERIC(10, 2) NOT NULL,
    total_amount NUMERIC(10, 2) NOT NULL,
    currency VARCHAR(3) NOT NULL,
    estimated_prep_minutes INTEGER NOT NULL,
    idempotency_key VARCHAR(80) NOT NULL,
    idempotency_fingerprint VARCHAR(64) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_orders_number UNIQUE (order_number),
    CONSTRAINT uq_orders_idempotency UNIQUE (customer_id, idempotency_key),
    CONSTRAINT ck_orders_type CHECK (order_type IN ('PICKUP', 'DELIVERY')),
    CONSTRAINT ck_orders_status CHECK (status IN ('PLACED', 'ACCEPTED', 'PREPARING', 'READY', 'COMPLETED', 'REJECTED', 'CANCELLED')),
    CONSTRAINT ck_orders_money CHECK (subtotal >= 0 AND tax_amount >= 0 AND delivery_fee >= 0 AND total_amount >= 0)
);

CREATE INDEX idx_orders_customer_created ON customer_orders (customer_id, created_at DESC);
CREATE INDEX idx_orders_branch_status ON customer_orders (branch_id, status);
CREATE INDEX idx_orders_created ON customer_orders (created_at);

CREATE TABLE order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES customer_orders (id),
    menu_item_id BIGINT NOT NULL REFERENCES menu_items (id),
    item_name VARCHAR(120) NOT NULL,
    unit_price NUMERIC(10, 2) NOT NULL,
    quantity INTEGER NOT NULL,
    line_total NUMERIC(10, 2) NOT NULL,
    vegetarian BOOLEAN NOT NULL,
    CONSTRAINT ck_order_items_qty CHECK (quantity > 0 AND quantity <= 20)
);

CREATE INDEX idx_order_items_order ON order_items (order_id);

CREATE TABLE payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES customer_orders (id),
    status VARCHAR(32) NOT NULL,
    amount NUMERIC(10, 2) NOT NULL,
    currency VARCHAR(3) NOT NULL,
    provider VARCHAR(16) NOT NULL,
    provider_reference VARCHAR(64) NOT NULL,
    failure_reason VARCHAR(300),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_payments_order UNIQUE (order_id),
    CONSTRAINT uq_payments_reference UNIQUE (provider_reference),
    CONSTRAINT ck_payments_status CHECK (status IN ('PENDING', 'SUCCESS', 'FAILED', 'CANCELLED'))
);

CREATE TABLE order_status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES customer_orders (id),
    from_status VARCHAR(32),
    to_status VARCHAR(32) NOT NULL,
    changed_by BIGINT NOT NULL REFERENCES users (id),
    note VARCHAR(300),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_history_order ON order_status_history (order_id, created_at);
